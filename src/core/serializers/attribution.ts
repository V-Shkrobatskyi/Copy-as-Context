import { version } from '../../../package.json';
import { COMPRESSION_LEVELS, type CompressionLevel } from '..';
import { BUILTIN_FILTERS, builtinCaseSensitive, defaultRedactionSettings, validateRedactionSettings, type RedactionSettings } from '../privacy/settings';

/** The low bit records the requested privacy setting; other bits encode the profile. */
export function renderExportSettings(level?: CompressionLevel, redactSensitiveData = false, redactionSettings?: RedactionSettings): string {
  const settings = level === undefined ? ''
    : `/${COMPRESSION_LEVELS.indexOf(level) * 2 + Number(redactSensitiveData)}`;
  let filters = '';
  if (level !== undefined && redactSensitiveData) {
    const defaults = defaultRedactionSettings();
    const config = redactionSettings === undefined ? defaults : validateRedactionSettings(redactionSettings);
    const isDefault = config.customRules.length === 0 && BUILTIN_FILTERS.every(filter =>
      config.disabledBuiltins.includes(filter.id) === defaults.disabledBuiltins.includes(filter.id) &&
      builtinCaseSensitive(config, filter.id) === builtinCaseSensitive(defaults, filter.id));
    filters = isDefault ? '/d' : '/m';
  }
  return `${settings}${filters}`;
}

export function renderExportAttribution(level?: CompressionLevel, redactSensitiveData = false, redactionSettings?: RedactionSettings): string {
  return `Generated by browser extension "Page as Context" ${version}${renderExportSettings(level, redactSensitiveData, redactionSettings)} (created by V. Shkrobatskyi)`;
}
